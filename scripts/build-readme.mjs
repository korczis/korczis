#!/usr/bin/env node
// Derives README.md, the GitHub profile page of korczis, from https://korczis.github.io/site.json
// (schema korczis-hub-site/v1): the site is the source, this page a projection of it. Nothing here
// is typed by hand; change the site and the next run (.github/workflows/readme.yml) follows.
//
// Layout: while the site says the owner is available (site.hire), the page leads with the one
// positioning (hire.headline) and a way to hire, then the proof (featured work, experience), then
// the long lists folded into <details>. Without site.hire it leads with the site's description.
//
// usage: node scripts/build-readme.mjs           write README.md
//        node scripts/build-readme.mjs --check   exit 1 if README.md is stale
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = process.env.SITE_JSON || 'https://korczis.github.io/site.json';
const FEATURED_OPEN = 6;   // featured projects shown before the fold
const EXPERIENCE_OPEN = 5; // roles shown before the fold

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE}: HTTP ${response.status}`);
const site = await response.json();
if (site.schema !== 'korczis-hub-site/v1') throw new Error(`${SOURCE}: unknown schema ${site.schema}`);

const base = site.url.replace(/\/$/, '');
const host = (url) => url.replace(/^https?:\/\//, '').replace(/\/$/, '');
const cell = (text) => String(text ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const byCategory = new Map(site.categories.map((c) => [c.key, c]));
const { author, hire } = site;

const fold = (summary, body) => body.length
  ? ['<details>', `<summary>${summary}</summary>`, '', ...body, '', '</details>', '']
  : [];

// The contact line: site first, then hire terms, LinkedIn, email, the Czech version.
const contact = [
  `**[${host(site.url)}](${site.url})**`,
  hire && `[Hire: terms and evidence](${hire.url})`,
  author.linkedin && `[LinkedIn](${author.linkedin})`,
  author.email && `[${author.email}](mailto:${author.email})`,
  `[Česky](${base}/cs/)`,
  author.location,
].filter(Boolean).join(' · ');

const rate = hire?.rate ? ` · contract rate from ${hire.rate.currency} ${hire.rate.from}/${hire.rate.unit}` : '';
const hireBlock = hire ? [
  `> **Open to work** · ${hire.engagement.join(', ')} · ${hire.workplace}, ${hire.regions}${rate}.`,
  '>',
  `> **[See terms, evidence and how to start →](${hire.url})**`,
  '',
  '## What I do',
  '',
  ...hire.roles.map((r) => `- ${cell(r)}`),
  '',
] : [];

const projectRow = (p) => {
  const stack = (p.stack ?? []).map(cell).join(', ');
  const live = p.site ? `[${cell(host(p.site))}](${p.site})` : '';
  return `| [**${cell(p.name)}**](${p.repo}) | ${cell(p.tagline)} | ${stack} | ${live} |`;
};
const projectTable = (list) => list.length
  ? ['| Project | What it is | Stack | Live |', '| --- | --- | --- | --- |', ...list.map(projectRow)]
  : [];

const years = (r) => `${r.start.slice(0, 4)}${r.end ? `–${r.end.slice(0, 4)}` : '–present'}`;
const role = (r) => `- **${cell(r.title)}**, ${r.url ? `[${cell(r.organisation)}](${r.url})` : cell(r.organisation)} (${years(r)})`;
const experience = site.experience ?? [];

const fields = site.categories
  .filter((c) => c.repositories > 0)
  .sort((a, b) => b.repositories - a.repositories)
  .map((c) => `- **[${cell(c.name)}](${c.url})** (${c.repositories}): ${cell(c.description)}`);

const lead = hire ? hire.headline : site.description;
const lines = [
  '<!-- generated by scripts/build-readme.mjs from https://korczis.github.io/site.json; do not edit -->',
  `<a href="${site.url}"><img src="${base}/og/home.png" alt="${cell(site.name)}: ${cell(lead)}" width="100%"></a>`,
  '',
  `# ${site.name}`,
  '',
  `**${lead}**`,
  ...(hire ? ['', site.description] : []),
  '',
  contact,
  '',
  ...hireBlock,
  '## Featured work',
  '',
  ...projectTable(site.projects.slice(0, FEATURED_OPEN)),
  '',
  ...fold(`${site.projects.length - FEATURED_OPEN} more featured projects`,
    projectTable(site.projects.slice(FEATURED_OPEN))),
  ...(experience.length ? [
    '## Experience',
    '',
    ...experience.slice(0, EXPERIENCE_OPEN).map(role),
    '',
    ...fold(`Earlier roles (${experience.length - EXPERIENCE_OPEN})`,
      experience.slice(EXPERIENCE_OPEN).map(role)),
  ] : []),
  '## Work by field',
  '',
  `${site.counts.own} original repositories on GitHub and GitLab, each with its sources, on [the site](${base}/repositories/);`,
  `forks (${site.counts.forks}) and mirrors (${site.counts.mirrors}) are left out.`,
  '',
  ...fold(`${fields.length} fields`, fields),
  `<sub>Derived from [site.json](${base}/site.json), data as of ${site.data_as_of.index.slice(0, 10)}.</sub>`,
  '',
];
const text = lines.join('\n');
if (byCategory.size !== site.categories.length) throw new Error('duplicate category keys');

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync('README.md', 'utf8'); } catch {}
  if (current !== text) { console.error('README.md is stale: run node scripts/build-readme.mjs'); process.exit(1); }
  console.log('README.md is current');
} else {
  writeFileSync('README.md', text);
  console.log(`README.md written: ${site.projects.length} projects, ${site.categories.length} categories`);
}
